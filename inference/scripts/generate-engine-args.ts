/**
 * Render the active service profile into vLLM engine arguments.
 *
 * Compose cannot probe a GPU or divide by total VRAM, and a checked-in constant would be
 * wrong on every card except the one it was written for — vLLM budgets as
 * `ceil(total × utilization)` and aborts when free memory at launch falls below that
 * product. So this script does the arithmetic at deploy time and writes an env file that
 * `docker-compose.yml` consumes.
 *
 * All decisions come from @saip/shared ProfileService — the same service the CLI and the
 * gateways use — so there is exactly one implementation of "what this card can run".
 *
 * Usage:
 *   npx tsx inference/scripts/generate-engine-args.ts
 *   SAIP_PROFILE=full-loop-12gb npx tsx inference/scripts/generate-engine-args.ts
 *
 * Writes `inference/.engine-args.env` and prints the resolved plan to stdout. Exits 2 on
 * insufficient GPU (matching the documented CLI exit code) rather than emitting args that
 * would OOM.
 */

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve, dirname } from 'node:path'
import {
  NvidiaSmiProbe,
  renderVllmArgs,
  GpuProbeError,
  type ProfileMap,
} from '@saip/shared'
import { ProfileService } from '@saip/shared/services'
import { Context } from 'cordis'
import { loadConfig } from '../src/lib/config.js'

const here = dirname(fileURLToPath(import.meta.url))
const outPath = resolve(here, '../.engine-args.env')

const SERVED_NAMES = (process.env.SAIP_SERVED_NAMES ?? 'saip-instruct saip-systemone').split(/\s+/).filter(Boolean)

/** Exit codes mirror docs/guides/cli-reference: 2 = GPU unavailable or insufficient VRAM. */
const EXIT_OK = 0
const EXIT_ERROR = 1
const EXIT_GPU = 2

function die(message: string, code = EXIT_ERROR): never {
  console.error(`[engine-args] ${message}`)
  process.exit(code)
}

async function main(): Promise<void> {
  const config = loadConfig(process.env.SAIP_CONFIG ?? resolve(here, '../../saip.yaml'))
  const profiles = config.profiles as ProfileMap
  if (!Object.keys(profiles).length) die('no profiles declared in saip.yaml (add a `profiles:` block)')

  const requested = process.env.SAIP_PROFILE ?? config.profile
  const ctx = new Context()
  await ctx.plugin(ProfileService, {
    profiles,
    profile: requested,
    probe: new NvidiaSmiProbe(),
  })
  const profiles0 = (ctx as any).profiles as InstanceType<typeof ProfileService>

  const declared = profiles0.assertValid()
  if (declared.length) {
    for (const e of declared) console.error(`[engine-args] ${e.path}: ${e.message}`)
    die(`${declared.length} invalid profile declaration(s) in saip.yaml`)
  }

  const resolution = await profiles0.resolve()
  if (!resolution.ok) {
    console.error(`[engine-args] ${resolution.error.code}: ${resolution.error.message}`)
    die('cannot resolve a service profile for this GPU', EXIT_GPU)
  }

  const { profile: name, args: profile, gpu, auto } = resolution
  console.log(`[engine-args] GPU: ${gpu.name} — ${gpu.total_gib} GiB total, ${gpu.free_gib} GiB free, compute capability ${gpu.capability}`)
  console.log(`[engine-args] Profile: ${name}${auto ? ' (auto-resolved)' : ' (explicit)'}`)

  const util = await profiles0.utilization()
  if (!util.ok) {
    console.error(`[engine-args] ${util.error.code}: ${util.error.message}`)
    die('this GPU cannot hold the resolved profile ceiling', EXIT_GPU)
  }
  console.log(`[engine-args] Derived --gpu-memory-utilization=${util.utilization} (ceiling ${profile.vram_ceiling_gib} GiB / total ${gpu.total_gib} GiB)`)

  let argv: string[]
  try {
    argv = renderVllmArgs(profile, {
      model: config.model.base,
      servedNames: SERVED_NAMES,
      utilization: util.utilization,
      capability: gpu.capability,
      port: 8000,
    })
  } catch (err) {
    die(`refusing to render engine args: ${(err as Error).message}`, EXIT_ERROR)
  }

  const engineArgs = argv.join(' ')
  writeFileSync(outPath, `# Generated by inference/scripts/generate-engine-args.ts — do not edit.\n# Profile: ${name} | GPU: ${gpu.name} | ${gpu.total_gib} GiB total, ${gpu.free_gib} GiB free, cc ${gpu.capability}\nENGINE_ARGS=${engineArgs}\nVLLM_MODEL=${config.model.base}\n`)

  console.log(`[engine-args] wrote ${outPath}`)
  console.log(`[engine-args] ENGINE_ARGS=${engineArgs}`)
  process.exit(EXIT_OK)
}

// A GPU we cannot read, or a card that cannot hold the resolved profile, is the documented
// exit-2 case — report it as a one-line diagnosis, never as a stack trace. Anything else
// is a bug and does get the trace.
main().catch((err) => {
  if (err instanceof GpuProbeError) die(err.message, EXIT_GPU)
  die(`unexpected failure: ${(err as Error).stack ?? String(err)}`)
})
