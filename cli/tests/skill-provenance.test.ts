/**
 * A tracked skill is an interface contract on THIS repository (#188).
 *
 * `.dsh/skills/local-llm/SKILL.md` was committed in `b8fcac2` describing **another project** —
 * dsh-chapters' dev platform. Its central instruction was:
 *
 *     cd dev/install && docker compose up -d
 *
 * `dev/install` does not exist in this repository. Neither do `dsh-test`, `dsh-web`,
 * `corpus:heal`, `E2E_MODEL`, `VLLM_GPU_MEM` or `qwen3-4b-instruct`. It was not merely stale prose:
 * an agent session rooted at saip read it and went looking for another repo's container stack.
 *
 * Nothing checked. `pnpm --filter @saip/docs build` renders pages and resolves links between them —
 * the docs referring to themselves — and `cli/tests/docs-flag-parity.test.ts` (#162) compares a
 * documented flag with the flags the built program accepts. Neither has ever asked whether a path a
 * skill tells you to `cd` into exists, because a skill is not a docs page: it is loaded into an
 * agent's context and executed as instruction.
 *
 * Three rules, each earned the hard way:
 *
 *   1. no loaded skill may name another project's toolchain (marker list below);
 *   2. every path a skill presents as a command argument must resolve — against the repo root OR
 *      the skill's own directory, because `render-graphs.js` legitimately means "in this
 *      directory";
 *   3. every `pnpm`/`npm` script a skill runs must appear in some workspace manifest.
 *
 * Scope is each skill's `SKILL.md` — the file an agent actually loads (see `loadedSkillFiles`).
 * Supporting files under `references` are NOT checked here: this guard's first run found a real
 * offender there — `.dsh/skills/github-ops/` + `references/ecc-release-checklist.md`, which
 * operates on the `ecc-universal` package and `tests/scripts/build-opencode.test.js` — and drawing
 * that into this PR would bundle a second project's audit under one issue. Filed as #189; the
 * boundary is deliberate, not an oversight, and the scope itself is asserted by a test rather
 * than left to a comment. (CI typechecks none of this file's types — that gap is #190, so the
 * strict `tsc --noEmit` run proving this file compiles was made by hand.)
 *
 * Prose is path-checked for the marker rule only. Illustrative filenames in prose — `docs/file1.md`
 * in a vendored best-practices doc — are not claims about this checkout, and a guard that cries
 * wolf gets switched off. Commands in `bash` fences are where a reader is told to act, so those
 * path claims are held to existence.
 *
 * The self-test matters as much as the scan: a guard that only ever runs against clean files is a
 * guard nobody has seen fail. `PREVIOUSLY_SHIPPED_SKILL` is the pre-fix text, quoted from `b8fcac2`,
 * and it MUST produce violations — including the `coverage:ci` script and the `dev/install` path.
 */
import { describe, it, expect } from 'vitest'
import { execFileSync } from 'node:child_process'
import { readFileSync, existsSync } from 'node:fs'
import { dirname, join, posix } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..')

/**
 * Identifiers owned by other projects on this machine. Deliberately a list rather than inference:
 * `treeseed-project` is a legitimate example adapter NAME in `docs/**` and `training/tests/**`, and
 * the note in `inference/docker-compose.yml` about host port 8080 is real rationale about saip's own
 * port choice. Both stay. What may not stay is a loaded skill instructing a reader to operate the
 * other project.
 */
const FOREIGN_MARKERS = [
  'dsh-chapters', 'treeseed-ai', '@treeseed', 'dev/install', 'dsh-web', 'dsh-test', 'dsh web',
  'corpus:heal', 'corpus:record', 'test:e2e', 'E2E_MODEL', 'E2E_TAPE', 'E2E_UPSTREAM', 'E2E_HOME',
  'VLLM_GPU_MEM', 'VLLM_SERVED_NAMES', 'VLLM_MODEL_ID', 'VLLM_MAX_MODEL_LEN',
  'qwen3-4b-instruct', 'qwen3-4b-systemone', 'PLAYWRIGHT_BROWSERS_PATH', 'ms-playwright',
] as const

/** Paths that exist only at runtime — generated by the tooling, or written by the user's shell. */
const RUNTIME_ONLY = ['inference/.engine-args.env', '.env']

/** npm/pnpm subcommands that are not package scripts, so their absence from a manifest means nothing. */
const BUILTIN_SUBCOMMANDS = new Set([
  'run', 'install', 'i', 'ci', 'add', 'remove', 'uninstall', 'update', 'build', 'test', 'lint',
  'start', 'stop', 'restart', 'exec', 'dlx', 'init', 'create', 'publish', 'pack', 'view', 'list',
  'ls', 'why', 'outdated', 'doctor', 'config', 'link', 'prune', 'cache', 'fund', 'audit', 'fix',
  'dedupe', 'show', 'info', 'search', 'token', 'login', 'logout', 'whoami', 'deprecate', 'dist-tag',
  'npm', 'pnpm', 'pnpm-workspace.yaml', 'package.json', 'vite', 'vitest', 'tsx', 'node', 'next', 'deploy',
])

/** Word chars, dot, slash, dash, at. Built via `new RegExp` because `/` inside a character class is
 *  not portable across regex-literal parsers — esbuild rejects `[a/-]` in a literal, and a guard
 *  that cannot be compiled is a guard that silently never runs. */
const TOK = '[A-Za-z0-9_./@-]'
const PATH_GLOBAL = new RegExp(
  `(?:^|[\\s;&|(])(?:cd|cat|cp|ls|touch|mkdir|source|node|npx\\s+tsx|tsx)\\s+(${TOK}+)`
  + `|(?:^|[\\s;])-f\\s+(${TOK}+)`,
  'g',
)

export interface Violation {
  file: string
  line: number
  kind: 'foreign-marker' | 'missing-path' | 'unknown-script'
  detail: string
}

function fences(text: string): Array<{ lang: string; body: string; start: number }> {
  const out: Array<{ lang: string; body: string; start: number }> = []
  const re = /^```([a-zA-Z0-9]*)\n([\s\S]*?)\n```/gm
  let m: RegExpExecArray | null
  while ((m = re.exec(text)) !== null) {
    out.push({ lang: m[1]!.toLowerCase(), body: m[2]!, start: text.slice(0, m.index).split('\n').length })
  }
  return out
}

const isBashish = (lang: string): boolean =>
  lang === '' || lang === 'bash' || lang === 'sh' || lang === 'shell' || lang === 'console'

/** Path arguments named by a command line. Absolute paths, URLs, image tags, env assignments and
 *  anything escaping the checkout (`../…`) are skipped: this rule is about claims on THIS repo. */
function pathClaims(line: string): string[] {
  const found: string[] = []
  for (const m of line.matchAll(PATH_GLOBAL)) {
    const tok = (m[1] ?? m[2] ?? '').trim().replace(/\/+$/, '')
    if (!tok || !tok.includes('/')) continue
    if (tok.startsWith('/') || tok.startsWith('../') || tok.startsWith('~/')) continue
    if (tok.includes('://') || tok.includes('<') || tok.includes('*') || tok.includes('=')) continue
    if (tok.includes(':')) continue // a container image tag, not a path
    found.push(tok)
  }
  return found
}

function scriptClaims(line: string): string[] {
  const out: string[] = []
  for (const m of line.matchAll(/(?:pnpm|npm)\s+(?:(?:--filter|--package)\s+\S+\s+)?(?:run\s+)?([a-z][\w:-]*)/g)) {
    const name = m[1]!
    if (BUILTIN_SUBCOMMANDS.has(name)) continue
    out.push(name)
  }
  return out
}

/** Every script name declared anywhere in the workspace. */
function knownScripts(): Set<string> {
  const names = new Set<string>()
  const files = execFileSync('git', ['-C', repoRoot, 'ls-files', '*package.json'], { encoding: 'utf8' })
    .split('\n').filter((f) => f && !f.includes('node_modules'))
  for (const rel of files) {
    try {
      const pkg = JSON.parse(readFileSync(join(repoRoot, rel), 'utf8')) as { scripts?: Record<string, string> }
      for (const k of Object.keys(pkg.scripts ?? {})) names.add(k)
    } catch { /* an unreadable manifest is not this guard's problem */ }
  }
  return names
}

/** Scan one loaded skill. Pure and exported so the failure mode is assertable without a fixture file. */
export function scanSkillText(text: string, file: string, scripts: Set<string>): Violation[] {
  const v: Violation[] = []
  const skillDir = posix.dirname(file) // repo-relative, e.g. `.dsh/skills/local-llm`

  text.split('\n').forEach((line, i) => {
    const low = line.toLowerCase()
    for (const marker of FOREIGN_MARKERS) {
      if (low.includes(marker.toLowerCase())) {
        // A negation still names the thing: "there is no dev/install here" trips this rule on
        // purpose (#188's own first draft was caught by its own guard). Say so in the text instead
        // of quoting the foreign path.
        v.push({ file, line: i + 1, kind: 'foreign-marker', detail: `names another project's toolchain: "${marker}" — even to deny it; describe saip's own layout instead` })
      }
    }
  })

  for (const f of fences(text)) {
    if (!isBashish(f.lang)) continue
    f.body.split('\n').forEach((line, i) => {
      for (const claim of pathClaims(line)) {
        if (RUNTIME_ONLY.includes(claim)) continue
        const clean = claim.replace(/^\.\//, '')
        const atRoot = existsSync(join(repoRoot, clean))
        const atSkillDir = existsSync(join(repoRoot, skillDir, clean))
        if (!atRoot && !atSkillDir) {
          v.push({ file, line: f.start + i, kind: 'missing-path', detail: `tells the reader to use ${claim}, which resolves neither in this checkout nor in ${skillDir}` })
        }
      }
      for (const name of scriptClaims(line)) {
        if (scripts.size > 0 && !scripts.has(name)) {
          v.push({ file, line: f.start + i, kind: 'unknown-script', detail: `runs script "${name}", which no workspace package.json declares` })
        }
      }
    })
  }

  return v
}

/** Files an agent is actually loaded with: the `SKILL.md` entry point of each skill. */
export function loadedSkillFiles(): string[] {
  return execFileSync('git', ['-C', repoRoot, 'ls-files', '.dsh/skills'], { encoding: 'utf8' })
    .split('\n').filter((f) => f.endsWith('/SKILL.md'))
}

/** The pre-fix text, quoted from `b8fcac2`. This MUST fail the scan. */
const PREVIOUSLY_SHIPPED_SKILL = [
  '---',
  'name: local-llm',
  'description: Local vLLM model server (Qwen3-4B-AWQ) with dual inference/systemone endpoints,',
  '  Docker Compose stack management, and test runner operations for the dsh-chapters dev platform.',
  'whenToUse: When working with the local LLM server, running or managing the Docker Compose stack',
  '  (vllm, dsh-web, dsh-test) ... in dev/install/.',
  '---',
  '',
  'The `dev/install/` directory is a self-contained development and test platform for',
  'dsh-chapters: DSH Web UI, local vLLM model server, and CI test runner.',
  '',
  '```bash',
  'cd dev/install && docker compose up -d',
  '```',
  '',
  '```bash',
  'docker compose run --rm dsh-test npm run test:e2e:replay',
  'docker compose run --rm dsh-test npm run coverage:ci',
  '```',
  '',
  '| Variable | Default |',
  '|----------|---------|',
  '| `VLLM_MODEL_ID` | `Qwen/Qwen3-4B-AWQ` |',
  '| `VLLM_GPU_MEM` | `0.90` |',
  '',
  'Native install (no Docker): `./dev/install/install.sh`',
  '',
].join('\n')

const OLD_SKILL_FILE = '.dsh/skills/local-llm/SKILL.md'

describe('skill provenance — a loaded skill must describe this repository (#188)', () => {
  const scripts = knownScripts()

  it('has a failing state: it rejects the skill that actually shipped', () => {
    const found = scanSkillText(PREVIOUSLY_SHIPPED_SKILL, OLD_SKILL_FILE, scripts)
    const kinds = new Set(found.map((x) => x.kind))
    expect(kinds.has('foreign-marker'), 'the old skill named dsh-chapters and dev/install').toBe(true)
    expect(kinds.has('missing-path'), 'the old skill told readers to cd into a directory that is not here').toBe(true)
    expect(kinds.has('unknown-script'), 'the old skill ran scripts no manifest declares').toBe(true)
    expect(found.length, `expected several violations, got ${String(found.length)}`).toBeGreaterThan(5)
    // Specific, so a future refactor cannot quietly make the guard blind while still "passing".
    expect(found.some((x) => x.detail.includes('dev/install'))).toBe(true)
    expect(found.some((x) => x.kind === 'unknown-script' && x.detail.includes('coverage:ci'))).toBe(true)
    expect(found.some((x) => x.kind === 'unknown-script' && x.detail.includes('test:e2e:replay'))).toBe(true)
  })

  it('does NOT fire on a legitimate relative script (regression: render-graphs.js)', () => {
    // `node ./render-graphs.js` means "in this directory" and the file is committed there.
    const text = '```bash\nnode ./render-graphs.js ../some-skill\n```\n'
    expect(scanSkillText(text, '.dsh/skills/writing-skills/SKILL.md', scripts)).toEqual([])
  })

  it('does NOT fire on npm built-ins (regression: `npm view ecc-universal`)', () => {
    const text = '```bash\nnpm view ecc-universal dist-tags --json\n```\n'
    expect(scanSkillText(text, '.dsh/skills/github-ops/SKILL.md', scripts)).toEqual([])
  })

  it('the corrected local-llm skill is clean', () => {
    const text = readFileSync(join(repoRoot, OLD_SKILL_FILE), 'utf8')
    const found = scanSkillText(text, OLD_SKILL_FILE, scripts)
    expect(found, found.map((x) => `${x.file}:${x.line} ${x.kind}: ${x.detail}`).join('\n')).toEqual([])
  })

  it('every loaded skill is clean, not only the one that broke', () => {
    const files = loadedSkillFiles()
    expect(files.length, 'no SKILL.md found — the guard would pass vacuously').toBeGreaterThan(3)
    expect(files.some((f) => f.endsWith('local-llm/SKILL.md')), 'local-llm must be in scope').toBe(true)
    const offenders = files
      .map((f) => scanSkillText(readFileSync(join(repoRoot, f), 'utf8'), f, scripts))
      .filter((v) => v.length > 0)
      .flat()
    expect(offenders, offenders.map((x) => `${x.file}:${x.line} ${x.kind}: ${x.detail}`).join('\n')).toEqual([])
  })
})
